"""
Serializers do two things:

1. SERIALIZATION (Python → JSON):
   When a view returns data, the serializer converts a Django model instance
   into a Python dict, which DRF then converts to JSON for the HTTP response.

   model_instance → serializer.data → {"id": 1, "title": "My Doc", ...}

2. DESERIALIZATION + VALIDATION (JSON → Python):
   When a view receives incoming data, the serializer validates it
   and converts it into a form suitable for saving to the database.

   {"title": "My Doc"} → serializer.is_valid() → serializer.save()

If validation fails, serializer.errors contains field-level error messages.
"""
import os

from django.contrib.auth.models import User
from rest_framework import serializers

from .models import Document, QueryLog, UserSession


# ─── AUTH SERIALIZERS ─────────────────────────────────────────────────────────

class RegisterSerializer(serializers.ModelSerializer):
    """
    Validates user registration input.

    ModelSerializer automatically creates fields that match the model,
    but we override 'password' to add extra rules (write-only, min length).
    """

    # write_only=True: this field appears in INPUT but is NEVER included in
    # the response JSON. Passwords must never be sent back to the client.
    password = serializers.CharField(
        write_only=True,
        min_length=8,
        style={'input_type': 'password'},
    )
    password_confirm = serializers.CharField(
        write_only=True,
        style={'input_type': 'password'},
    )

    class Meta:
        model = User
        fields = ['username', 'email', 'password', 'password_confirm']

    def validate(self, data):
        """
        validate() runs AFTER each individual field is validated.
        Use it for cross-field validation (comparing multiple fields together).
        Raise serializers.ValidationError to reject the input with HTTP 400.
        """
        if data['password'] != data['password_confirm']:
            raise serializers.ValidationError({
                'password_confirm': 'Passwords do not match.',
            })
        return data

    def create(self, validated_data):
        """
        Called by serializer.save() after all validation passes.

        create_user() is Django's method for creating users.
        It automatically HASHES the password — the plain-text password
        is NEVER stored in the database. Always use create_user(), never User().
        """
        validated_data.pop('password_confirm')  # remove before passing to User
        user = User.objects.create_user(
            username=validated_data['username'],
            email=validated_data.get('email', ''),
            password=validated_data['password'],
        )
        return user


class LoginSerializer(serializers.Serializer):
    """
    Validates login input.

    We use plain Serializer (not ModelSerializer) because login is not about
    creating or updating a model — it is just validating credentials.
    """
    username = serializers.CharField()
    password = serializers.CharField(write_only=True)


# ─── DOCUMENT SERIALIZER ──────────────────────────────────────────────────────

class DocumentSerializer(serializers.ModelSerializer):
    """
    Serializes/deserializes Document objects.

    For responses: converts Document instance → JSON dict.
    For requests:  validates incoming JSON/form data → saves Document to DB.
    """

    # ReadOnlyField: appears in responses but is ignored in input.
    # source='owner.username': navigates the ForeignKey to get the username string
    # instead of showing the owner's numeric ID.
    owner = serializers.ReadOnlyField(source='owner.username')

    class Meta:
        model = Document
        fields = ['id', 'title', 'content', 'file', 'uploaded_at', 'owner']
        # read_only_fields: included in responses, but ignored/auto-set for input.
        # - 'id': auto-generated by the database
        # - 'uploaded_at': set automatically by auto_now_add=True
        # - 'owner': set by the view (request.user), never from client input
        read_only_fields = ['id', 'uploaded_at', 'owner']

    def validate_title(self, value):
        """
        Field-level validator for 'title'.
        Django calls validate_<fieldname>() automatically during validation.
        """
        stripped = value.strip()
        if not stripped:
            raise serializers.ValidationError('Title cannot be blank.')
        return stripped

    def validate_file(self, value):
        """
        Field-level validator for 'file'.
        Checks file type. File size is checked in the view for HTTP 413.
        """
        if value is None:
            # File is optional — no validation needed
            return value

        # Check file extension
        from django.conf import settings as django_settings
        _, ext = os.path.splitext(value.name)
        ext_clean = ext.lstrip('.').lower()

        allowed = getattr(django_settings, 'ALLOWED_UPLOAD_EXTENSIONS', {'pdf', 'txt', 'docx', 'doc'})
        if ext_clean not in allowed:
            allowed_str = ', '.join(f'.{e}' for e in sorted(allowed))
            raise serializers.ValidationError(
                f'File type "{ext}" is not allowed. Allowed types: {allowed_str}.'
            )

        return value


# ─── QUERY LOG SERIALIZER ─────────────────────────────────────────────────────

class QueryLogSerializer(serializers.ModelSerializer):
    """
    Serializes/deserializes QueryLog objects.

    Input:  {"query_text": "What documents do I have?"}
    Output: {"id": 1, "query_text": "...", "result_summary": "", "created_at": "...", "user": "alice"}
    """

    # Shows the username string instead of the user's numeric ID
    user = serializers.ReadOnlyField(source='user.username')

    class Meta:
        model = QueryLog
        fields = ['id', 'query_text', 'result_summary', 'created_at', 'user']
        # result_summary and user are set by the system, not the client
        read_only_fields = ['id', 'result_summary', 'created_at', 'user']

    def validate_query_text(self, value):
        stripped = value.strip()
        if not stripped:
            raise serializers.ValidationError('Query text cannot be blank.')
        return stripped


